// URL первой фотографии карточки WB, вычисляемый напрямую из nmId — без похода
// в API и без токена. WB раскладывает фото по CDN-корзинам (basket-XX) по
// диапазону vol = floor(nmId/100000); ниже — таблица диапазонов, известная
// из практики продавцов WB. Список корзин у WB иногда расширяется (появляются
// новые basket-NN), тогда самые новые товары (с большим nmId) перестанут
// попадать в таблицу — в этом случае просто вернётся URL по последней известной
// корзине и картинка может не открыться; это не критично (в таблице просто
// не будет фото), но при появлении новых nmId-диапазонов таблицу стоит обновить.
const BASKET_RANGES = [
  [143, '01'], [287, '02'], [431, '03'], [719, '04'], [1007, '05'],
  [1061, '06'], [1115, '07'], [1169, '08'], [1313, '09'], [1601, '10'],
  [1655, '11'], [1919, '12'], [2045, '13'], [2189, '14'], [2405, '15'],
  [2621, '16'], [2837, '17'], [3053, '18'], [3269, '19'], [3485, '20'],
];

function wbPhotoUrl(nmId) {
  const id = Number(nmId);
  if (!id) return null;
  const vol = Math.floor(id / 100000);
  const part = Math.floor(id / 1000);
  const found = BASKET_RANGES.find(([max]) => vol <= max);
  const basket = found ? found[1] : BASKET_RANGES[BASKET_RANGES.length - 1][1];
  return `https://basket-${basket}.wbbasket.ru/vol${vol}/part${part}/${id}/images/c246x328/1.webp`;
}

module.exports = { wbPhotoUrl };
