function districtOf(region) {
  const r = String(region || '').toLowerCase();
  if (!r || r === 'не указан') return 'Не указан';
  for (const [d, keys] of DISTRICTS) if (keys.some(k => r.includes(k))) return d;
  return 'Прочие';
}
