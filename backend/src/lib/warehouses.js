// Склад Ozon → кластер (когда метод с кластерами недоступен и приходят
// только названия складов вида «НОВОСИБИРСК_РФЦ_НОВЫЙ», «ХОРУГВИНО_РФЦ»).
// Названия кластеров — как у Ozon в заказах (cluster_to).
const RULES = [
  [/ХОРУГВИНО|ПУШКИНО|ЖУКОВСК|ГРИВНО|НОГИНСК|ПЕТРОВСКОЕ|ДОМОДЕДОВ|ЛЮБЕРЦ|СОФЬИНО|ЧЕХОВ|МОСКВ|ПОДОЛЬСК|КЛИМОВСК|ЭЛЕКТРОУГЛ|БЕЛАЯ_?ДАЧА|ВНУКОВО|ОБУХОВО|ТВЕРСКАЯ|КОЛЕДИНО|ХИМКИ|ДЗЕРЖИНСК_МО|БЕЛЫЕ_?СТОЛБЫ|НЕКРАСОВКА|СТОЛБОВАЯ|ЩЁЛКОВО|ЩЕЛКОВО|ДМИТРОВ/, 'Москва, МО и Дальние регионы'],
  [/СПБ|САНКТ|ПЕТЕРБУРГ|ШУШАРЫ|БУГРЫ|КОЛПИНО|ПАРГОЛОВО|ВОЛХОНК|ЛЕНИНГРАД/, 'Санкт-Петербург и СЗО'],
  [/ХАБАРОВСК|ВЛАДИВОСТОК|ДАЛЬНИЙ/, 'Дальний Восток'],
  [/АЛМАТЫ|АСТАНА|КАЗАХСТАН/, 'Казахстан'],
  [/МИНСК|БЕЛАРУС/, 'Беларусь'],
  [/НИЖНИЙ_?НОВГОРОД|НИЖН/, 'Нижний Новгород'],
  [/РОСТОВ/, 'Ростов'],
];
const CITIES = ['Новосибирск', 'Казань', 'Самара', 'Екатеринбург', 'Краснодар', 'Воронеж', 'Омск', 'Красноярск', 'Тюмень', 'Уфа', 'Пермь',
  'Саратов', 'Оренбург', 'Калининград', 'Махачкала', 'Невинномысск', 'Ярославль', 'Тверь', 'Иркутск', 'Волгоград', 'Челябинск', 'Ижевск', 'Кемерово', 'Барнаул'];
function clusterOfWarehouse(name) {
  const n = String(name || '').toUpperCase().replace(/Ё/g, 'Е');
  if (!n) return 'Склад не указан';
  for (const [re, c] of RULES) if (re.test(n)) return c;
  for (const c of CITIES) if (n.includes(c.toUpperCase())) return c;
  return String(name);
}
module.exports = { clusterOfWarehouse };
