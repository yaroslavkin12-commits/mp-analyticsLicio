// Версия данных: растёт, когда сбор действительно что-то записал в базу
// (или пользователь что-то сохранил). Кэш тяжёлых отчётов живёт, пока версия
// не изменилась, — повторные открытия разделов не ходят в базу.
let version = 1;
module.exports = {
  bump() { version++; },
  get() { return version; },
};
