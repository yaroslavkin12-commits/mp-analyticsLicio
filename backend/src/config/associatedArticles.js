// "Склейки" Ozon — один рекламируемый артикул (в терминах Ozon Ads он же
// "родительский" в карточке) объединён с другими артикулами того же товара
// (обычно другой материал/комплектация — жаккард без буквы, "К" — экокожа,
// "КR"/"ZR" — экокожа ромб и т.п.). Реклама крутится только на одном
// артикуле склейки, но заказы приходят по ВСЕЙ склейке сразу, потому что
// покупатель на одной карточке видит все варианты и может заказать любой.
// Список задал пользователь вручную (Ozon API не отдаёт связку артикулов
// внутри склейки напрямую) — при добавлении новых артикулов в рекламу или
// изменении склейки нужно поправить этот файл.
//
// cabinet -> { рекламируемый offer_id -> [offer_id других вариантов склейки] }
const ASSOCIATED_ARTICLES = {
  defly: {
    'Hv4-2KR':     ['Hv4-2', 'Hv4-2K'],
    'Hnd1-2K':     ['Hnd1-2', 'Hnd1-2ZR', 'Hnd7-2', 'Hnd7-2K'],
    'V015-5-2KR':  ['V015-5-2'],
    'V017-2K':     ['V017-2', 'V017-2ZR'],
    'V020-2':      ['V020-2K', 'V021-2', 'V021-2K'],
    'Fr2-2K':      ['Fr2-2KR', 'Fr2-2'],
    'Fr1-2KR':     ['Fr1-2', 'Fr1-2C'],
    'V024-2K':     ['V024-2'],
    'V023-2K':     ['V023-2'],
    'Kia3-2K':     ['Kia3-2', 'Kia3-2-2K', 'Kia3-2-2'],
    'Vw1-2K':      ['Vw1-2', 'Vw2-2K'],
    'Rn1-2KR':     ['Rn1-2'],
    'Rn5-2':       ['Rn5-2KR', 'Rn6-2', 'Rn8-2', 'Rn8-2K'],
    'U2-2K':       ['U2-2'],
  },
};

function getAssociatedOfferIds(cabinet, offerId) {
  return (ASSOCIATED_ARTICLES[cabinet] && ASSOCIATED_ARTICLES[cabinet][offerId]) || [];
}

module.exports = { ASSOCIATED_ARTICLES, getAssociatedOfferIds };
